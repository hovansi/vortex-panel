import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import WebSocket from 'ws';
import { createApp } from '../server/index.js';

test('authenticated API, websocket updates and demo server operations connect end-to-end', async t => {
  const dataDir = await fs.mkdtemp(path.join(os.tmpdir(), 'bedrock-integration-'));
  const runtime = await createApp({ dataDir, demo: true });
  await new Promise(resolve => runtime.server.listen(0, '127.0.0.1', resolve));
  t.after(async () => { await runtime.close(); await fs.rm(dataDir, { recursive: true, force: true }); });
  const origin = `http://127.0.0.1:${runtime.server.address().port}`;
  assert.equal((await fetch(`${origin}/api/dashboard`)).status, 401);
  const authResponse = await fetch(`${origin}/api/auth/status`);
  const auth = await authResponse.json();
  assert.equal(auth.demo, true); assert.equal(auth.authenticated, true);
  const cookie = authResponse.headers.get('set-cookie').split(';')[0];
  const headers = { Cookie: cookie, Origin: origin, 'X-CSRF-Token': auth.csrfToken, 'Content-Type': 'application/json' };
  async function request(route, body, method = body ? 'POST' : 'GET') {
    const response = await fetch(`${origin}/api${route}`, { method, headers, ...(body ? { body: JSON.stringify(body) } : {}) });
    const data = await response.json();
    assert.equal(response.ok, true, `${method} ${route}: ${JSON.stringify(data)}`);
    return data;
  }
  const dashboard = await request('/dashboard');
  assert.ok(dashboard.servers.length > 0); assert.equal(dashboard.capabilities.demo, true);
  assert.ok(dashboard.host.memoryTotal > 0);
  const versions = await request('/versions'); assert.ok(versions.latest);
  const ws = new WebSocket(origin.replace('http:', 'ws:') + '/ws', { headers: { Cookie: cookie, Origin: origin } });
  const message = await new Promise((resolve, reject) => { ws.once('message', value => resolve(JSON.parse(value.toString()))); ws.once('error', reject); });
  assert.equal(message.type, 'update'); ws.close();
  const server = dashboard.servers[0];
  await request(`/servers/${server.id}/stop`, {});
  const properties = await request(`/servers/${server.id}/properties`);
  assert.ok(properties.properties['server-port']);
  await request(`/servers/${server.id}/files/mkdir`, { path: 'integration' });
  await request(`/servers/${server.id}/files/create`, { path: 'integration/test.txt', content: 'verified' });
  const file = await request(`/servers/${server.id}/file?path=integration/test.txt`);
  assert.equal(file.content, 'verified');
  const escaped = await fetch(`${origin}/api/servers/${server.id}/file?path=../panel.json`, { headers });
  assert.equal(escaped.ok, false);
  const schedule = await request('/schedules', { serverId: server.id, action: 'command', intervalMinutes: 60, command: 'list', enabled: true });
  assert.ok(schedule.schedule.id);
  await request(`/schedules/${schedule.schedule.id}`, null, 'DELETE');
  await request(`/servers/${server.id}/start`, {});
  await request(`/servers/${server.id}/command`, { command: 'list' });
  const logs = await request(`/servers/${server.id}/logs`); assert.ok(logs.logs.length);
  const hostTerminal = await fetch(`${origin}/api/host/terminal`, { method: 'POST', headers, body: JSON.stringify({ command: 'echo test' }) });
  assert.equal(hostTerminal.status, 403);
  const mutationNoCsrf = await fetch(`${origin}/api/servers/${server.id}/stop`, { method: 'POST', headers: { Cookie: cookie, 'Content-Type': 'application/json' }, body: '{}' });
  assert.equal(mutationNoCsrf.status, 403);
  assert.equal((await fetch(`${origin}/`)).status, 200);
});
