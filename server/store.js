import fs from 'node:fs';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import { getLogRetentionPolicy, validateLogRetentionPolicy, migrateLogRetentionSettings, retainStoreHistory, protectedHistoryRows, boundedUtf8Text, STORE_MAX_LOAD_BYTES } from './log-retention.js';
import { validateWorldName } from './worlds.js';

const uuid = '[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}';
const worldComponent = String.raw`[^/\\\x00-\x1f\x7f]{1,255}`;
const worldQuarantinePath = `servers/${uuid}/run/worlds/\\.vortex-delete-server-${worldComponent}-${uuid}`;
const worldQuarantineName = new RegExp(`^servers/${uuid}/run/worlds/\\.vortex-delete-server-(${worldComponent})-${uuid}$`, 'i');
const quarantinePath = `(?:servers/(?:\\.vortex-delete-server-${uuid}-${uuid}|${uuid}/backups/\\.vortex-delete-backup-${uuid}\\.zip-${uuid})|${worldQuarantinePath})`;
const orphanBackupPath = `servers/${uuid}/backups/${uuid}\\.zip`;
const backupSnapshotPath = `servers/${uuid}/backups/\\.${uuid}\\.snapshot`;
function pendingHistoryRecovery(dataDir) {
  const cache = new Map(), root = fs.realpathSync(dataDir);
  const present = relative => {
    if (cache.has(relative)) return cache.get(relative);
    const world = relative.match(worldQuarantineName);
    if (world) {
      try { validateWorldName(world[1]); }
      catch { cache.set(relative, false); return false; }
    }
    let current = root, exists = true;
    // Read metadata only for exact paths generated by owned deletion/backup
    // code. Never follow a link or scan/delete a runtime/user directory.
    for (const piece of relative.split('/')) {
      current = path.join(current, piece);
      try { if (fs.lstatSync(current).isSymbolicLink()) break; }
      catch (error) { if (error.code === 'ENOENT') exists = false; break; }
    }
    cache.set(relative, exists); return exists;
  };
  return record => {
    if (!record || typeof record !== 'object') return false;
    if (['server.delete', 'world.delete', 'backup.delete', 'backup.retention'].includes(record.action) && typeof record.detail === 'string') {
      const match = record.detail.match(new RegExp(` \\[quarantine: (${quarantinePath})\\]$`, 'i'));
      if (match && present(match[1])) return true;
    }
    if (typeof record.type !== 'string') return false;
    const texts = [record.message, ...(Array.isArray(record.warnings) ? record.warnings : [])];
    for (const text of texts) if (typeof text === 'string') {
      const pattern = new RegExp(`(?:còn dữ liệu cách ly tại |dữ liệu vẫn được cách ly tại )(${quarantinePath})(?=[.:]|\\s|$)|backup chưa được ghi vào catalog vẫn ở (${orphanBackupPath})(?=:)|Chưa dọn được dữ liệu sao lưu tạm tại (${backupSnapshotPath})(?=:)`, 'gi');
      for (const match of text.matchAll(pattern)) if (present(match[1] || match[2] || match[3])) return true;
    }
    return false;
  };
}

export function createStore(dataDir, { ephemeral = false, maxLoadBytes = STORE_MAX_LOAD_BYTES } = {}) {
  fs.mkdirSync(dataDir, { recursive: true, mode: 0o700 });
  const filename = path.join(dataDir, 'panel.json');
  const defaults = { schemaVersion: 1, users: [], servers: [], nodes: [], nodeProvisionJobs: [], versions: [], jobs: [], schedules: [], activity: [], settings: {} };
  let loaded = defaults;
  if (!ephemeral && fs.existsSync(filename)) {
    const stat = fs.lstatSync(filename);
    if (!stat.isFile() || stat.isSymbolicLink() || stat.nlink > 1) throw new Error('Panel store must be a regular unlinked file.');
    if (stat.size > maxLoadBytes) throw new Error(`Panel store exceeds the ${maxLoadBytes}-byte safe loading limit; preserve the original and review its history offline.`);
    loaded = { ...defaults, ...JSON.parse(fs.readFileSync(filename, 'utf8')) };
  }
  const data = loaded;
  for (const key of ['users', 'servers', 'nodes', 'nodeProvisionJobs', 'versions', 'jobs', 'schedules', 'activity']) if (!Array.isArray(data[key])) throw new Error(`Corrupt panel store: ${key} must be an array.`);
  for (const user of data.users) {
    user.id ||= randomUUID(); user.role ||= 'admin'; user.serverIds ||= [];
    user.allServers = user.role === 'admin' || user.allServers === true;
    user.disabled = Boolean(user.disabled); user.sessionVersion ||= 0;
  }
  data.schemaVersion = 2;
  if (!data.settings || typeof data.settings !== 'object' || Array.isArray(data.settings)) throw new Error('Corrupt panel store: settings must be an object.');
  migrateLogRetentionSettings(data);
  let lastRetention;
  const historyOptions = () => ({ isRecoveryAnchor: pendingHistoryRecovery(dataDir) });
  const retained = retainStoreHistory(data, undefined, historyOptions());
  data.activity = retained.activity; data.jobs = retained.jobs; lastRetention = retained.stats;
  const store = {
    data,
    save() {
      const candidate = retainStoreHistory(data, undefined, historyOptions());
      // Pruning participates in the same atomic commit. Do not replace history
      // arrays until rename succeeds; caller rollback keeps its prior references.
      if (!ephemeral) {
        const temp = path.join(dataDir, `.vortex-store-${randomUUID()}.tmp`);
        let descriptor, created = false;
        try {
          const serialized = JSON.stringify({ ...data, activity: candidate.activity, jobs: candidate.jobs }, null, 2);
          if (Buffer.byteLength(serialized) > maxLoadBytes) throw new Error(`Panel store exceeds the ${maxLoadBytes}-byte safe commit limit; active jobs and recovery data were preserved in memory.`);
          if (fs.existsSync(filename)) {
            const stat = fs.lstatSync(filename);
            if (!stat.isFile() || stat.isSymbolicLink() || stat.nlink > 1) throw new Error('Panel store must be a regular unlinked file.');
          }
          descriptor = fs.openSync(temp, fs.constants.O_WRONLY | fs.constants.O_CREAT | fs.constants.O_EXCL | (fs.constants.O_NOFOLLOW || 0), 0o600); created = true;
          fs.writeFileSync(descriptor, serialized);
          fs.closeSync(descriptor); descriptor = undefined;
          fs.renameSync(temp, filename);
        } finally {
          if (descriptor !== undefined) try { fs.closeSync(descriptor); } catch {}
          if (created) try { fs.unlinkSync(temp); } catch {}
        }
      }
      data.activity = candidate.activity; data.jobs = candidate.jobs; lastRetention = candidate.stats;
    },
    audit(action, detail, user = 'admin', detailI18n, serverId) {
      const previous = data.activity;
      const record = { id: randomUUID(), time: new Date().toISOString(), action, detail: boundedUtf8Text(typeof detail === 'string' ? detail : JSON.stringify(detail), 16384), user, ...(detailI18n ? { detailI18n } : {}), ...(typeof serverId === 'string' && serverId ? { serverId } : {}) };
      data.activity = [record, ...previous];
      try { store.save(); }
      catch (error) { data.activity = previous; throw error; }
    },
    historyPolicy() { return getLogRetentionPolicy(data.settings.logRetention); },
    historyStats() {
      const current = retainStoreHistory(data, undefined, historyOptions());
      return { policy: store.historyPolicy(), activityEntries: data.activity.length, activityBytes: Buffer.byteLength(JSON.stringify(data.activity)), jobEntries: data.jobs.length, jobBytes: Buffer.byteLength(JSON.stringify(data.jobs)), protectedActivityEntries: current.stats.activity.protectedEntries, protectedJobEntries: current.stats.jobs.protectedEntries, protectedOverBudget: current.stats.activity.protectedOverBudget || current.stats.jobs.protectedOverBudget, lastRetention };
    },
    updateHistoryPolicy(input, user = 'admin') {
      const policy = validateLogRetentionPolicy(input, data.settings.logRetention), previousSettings = data.settings;
      data.settings = { ...previousSettings, logRetention: policy, logRetentionCustomized: true, logRetentionDefaultsVersion: 2 };
      try { store.audit('logs.policy.update', JSON.stringify(policy), user); }
      catch (error) { data.settings = previousSettings; throw error; }
      return store.historyStats();
    },
    clearHistory(input, user = 'admin') {
      if (!input || typeof input !== 'object' || Array.isArray(input) || Object.keys(input).some(key => !['activity', 'finishedJobs', 'confirmed'].includes(key)) || input.confirmed !== true || (input.activity !== undefined && typeof input.activity !== 'boolean') || (input.finishedJobs !== undefined && typeof input.finishedJobs !== 'boolean') || (!input.activity && !input.finishedJobs)) throw Object.assign(new Error('History clearing requires explicit confirmation and a supported history selection.'), { status: 400 });
      const previousActivity = data.activity, previousJobs = data.jobs, protectedRows = protectedHistoryRows(data, historyOptions());
      if (input.activity) data.activity = data.activity.filter(record => protectedRows.activity.has(record));
      if (input.finishedJobs) data.jobs = data.jobs.filter(record => protectedRows.jobs.has(record));
      const cleared = { activity: previousActivity.length - data.activity.length, finishedJobs: previousJobs.length - data.jobs.length };
      try { store.audit('logs.history.clear', JSON.stringify(cleared), user); }
      catch (error) { data.activity = previousActivity; data.jobs = previousJobs; throw error; }
      return { ...cleared, stats: store.historyStats() };
    },
    exportHistory() { return { exportedAt: new Date().toISOString(), policy: store.historyPolicy(), activity: [...data.activity], jobs: [...data.jobs] }; },
  };
  if (!ephemeral && data.users.length) store.save();
  return store;
}
